import fs from "fs";
import path from "path";

export interface MigrationAuditResult {
  migrationName: string;
  forwardSqlPath: string;
  forwardSizeBytes: number;
  tablesCreated: string[];
  tablesModified: string[];
  indexesCreated: string[];
  rollbackSql: string;
}

export class MigrationAuditService {
  private static migrationsDir = fs.existsSync(path.join(__dirname, "..", "prisma", "migrations"))
    ? path.join(__dirname, "..", "prisma", "migrations")
    : path.join(__dirname, "..", "..", "prisma", "migrations");

  /**
   * Audit all migrations and generate reverse rollback DDL
   */
  public static auditAll(): MigrationAuditResult[] {
    const entries = fs.readdirSync(this.migrationsDir, { withFileTypes: true });
    const migrationDirs = entries
      .filter((e) => e.isDirectory())
      .map((e) => e.name)
      .sort();

    const results: MigrationAuditResult[] = [];

    for (const dirName of migrationDirs) {
      const sqlFile = path.join(this.migrationsDir, dirName, "migration.sql");
      if (!fs.existsSync(sqlFile)) continue;

      const content = fs.readFileSync(sqlFile, "utf-8");
      const tablesCreated: string[] = [];
      const tablesModified: string[] = [];
      const indexesCreated: string[] = [];

      // Extract CREATE TABLE
      const createTableRegex = /CREATE TABLE (?:IF NOT EXISTS )?"([^"]+)"/gi;
      let match;
      while ((match = createTableRegex.exec(content)) !== null) {
        tablesCreated.push(match[1]);
      }

      // Extract ALTER TABLE
      const alterTableRegex = /ALTER TABLE "([^"]+)"/gi;
      while ((match = alterTableRegex.exec(content)) !== null) {
        if (!tablesModified.includes(match[1])) {
          tablesModified.push(match[1]);
        }
      }

      // Extract CREATE INDEX
      const createIndexRegex = /CREATE (?:UNIQUE )?INDEX (?:IF NOT EXISTS )?"([^"]+)"/gi;
      while ((match = createIndexRegex.exec(content)) !== null) {
        indexesCreated.push(match[1]);
      }

      // Generate corresponding documented rollback SQL
      const rollbackSql = this.generateRollbackSql(dirName, tablesCreated, indexesCreated);

      results.push({
        migrationName: dirName,
        forwardSqlPath: sqlFile,
        forwardSizeBytes: content.length,
        tablesCreated,
        tablesModified,
        indexesCreated,
        rollbackSql,
      });
    }

    return results;
  }

  /**
   * Generate safe rollback SQL statements for a given migration
   */
  public static generateRollbackSql(
    migrationName: string,
    tablesCreated: string[],
    indexesCreated: string[]
  ): string {
    const lines: string[] = [
      `-- ==============================================================================`,
      `-- Rollback DDL for migration: ${migrationName}`,
      `-- Generated by KIBO360 Migration Audit Service`,
      `-- Organization: Livexpert Technologies Pvt. Ltd.`,
      `-- ==============================================================================`,
      `BEGIN;`,
      ``,
    ];

    // Drop indexes
    for (const idx of indexesCreated.reverse()) {
      lines.push(`DROP INDEX IF EXISTS "${idx}";`);
    }

    // Drop created tables (with CASCADE for foreign keys)
    for (const tbl of tablesCreated.reverse()) {
      lines.push(`DROP TABLE IF EXISTS "${tbl}" CASCADE;`);
    }

    // Custom migration-specific teardowns
    if (migrationName.includes("phase7")) {
      lines.push(`DROP TYPE IF EXISTS "NotificationType" CASCADE;`);
      lines.push(`DROP TYPE IF EXISTS "JobStatus" CASCADE;`);
    } else if (migrationName.includes("phase5")) {
      lines.push(`DROP TYPE IF EXISTS "AttachmentAccessScope" CASCADE;`);
    } else if (migrationName.includes("phase4")) {
      lines.push(`DROP TYPE IF EXISTS "ProjectPriority" CASCADE;`);
      lines.push(`DROP TYPE IF EXISTS "MilestoneStatus" CASCADE;`);
    } else if (migrationName.includes("phase2")) {
      lines.push(`DROP TYPE IF EXISTS "UserRole" CASCADE;`);
    }

    lines.push(``);
    lines.push(`COMMIT;`);
    return lines.join("\n");
  }
}

// CLI handler
if (require.main === module) {
  const audits = MigrationAuditService.auditAll();
  console.log(`Audited ${audits.length} migrations:`);
  for (const a of audits) {
    console.log(`\n📦 Migration: ${a.migrationName}`);
    console.log(`   Tables created: ${a.tablesCreated.join(", ") || "none"}`);
    console.log(`   Indexes created: ${a.indexesCreated.length}`);
    console.log(`   Rollback SQL generated: ${a.rollbackSql.length} chars`);
  }
}
